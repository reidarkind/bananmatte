const TABLES: Record<Locale, Record<string, string>> = { nb: NB, en: EN, ...EXTRA_LOCALES };

export function t(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  let text = TABLES[locale][key] ?? TABLES.nb[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function modeLabel(locale: Locale, id: ModeId | PlaySelection): string {
  return t(locale, `mode.${id}`);
}

export function playStyleLabel(locale: Locale, style: PlayStyleChoice): string {
  return t(locale, `play.${style}`);
}

export function overCopy(
  locale: Locale,
  style: PlayStyle,
  reason: "misses" | "rotten",
): { title: string; detail: string } {
  const kind = reason === "rotten" ? "rotten" : "miss";
  return {
    title: t(locale, `over.${kind}Title.${style}`),
    detail: t(locale, `over.${kind}Detail.${style}`),
  };
}
